/**
 * Resolves a 2-letter ISO country code from country name or alias.
 */
export function getCountryCode(name) {
    if (!name || typeof name !== 'string') return null;
    const clean = name.trim().toLowerCase();
    return COUNTRY_ISO_MAP[clean] || null;
}

/**
 * Returns FlagCDN URL for given ISO code.
 */
export function getCountryFlagImgUrl(code) {
    if (!code) return null;
    return `https://flagcdn.com/28x21/${code.toLowerCase()}.png`;
}

/**
 * Returns an accessible HTML badge containing the crisp flag icon.
 */
export function getCountryFlagHtml(name) {
    const code = getCountryCode(name);
    if (!code) return '';
    return `<span class="country-flag-icon inline-flex items-center justify-center w-4 h-3 mr-2 rounded-xs overflow-hidden flex-shrink-0 shadow-xs border border-white/10 bg-black/20 align-middle"><img src="https://flagcdn.com/28x21/${code}.png" srcset="https://flagcdn.com/56x42/${code}.png 2x" alt="${name}" width="16" height="12" class="w-full h-full object-cover" loading="lazy" onerror="this.parentElement.style.display='none';" /></span>`;
}
